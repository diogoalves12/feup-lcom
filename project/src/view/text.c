#define FONT_TABLE_LEN ((int)(sizeof(font_table) / sizeof(font_table[0])))

static const uint8_t *glyph_for(char ch) {
  if (ch >= 'a' && ch <= 'z') ch = (char)(ch - 'a' + 'A');
  for (int i = 0; i < FONT_TABLE_LEN; i++) {
    if (font_table[i].ch == ch) return font_table[i].rows;
  }
  return font_unknown;
}

int text_char_width(uint8_t scale) {
  if (scale == 0) scale = 1;
  return (TEXT_GLYPH_W + GLYPH_SPACING) * (int)scale;
}

int text_string_width(const char *str, uint8_t scale) {
  if (str == NULL) return 0;
  int count = 0;
  while (str[count] != '\0') count++;
  if (count == 0) return 0;
  if (scale == 0) scale = 1;
  return count * TEXT_GLYPH_W * (int)scale + (count - 1) * GLYPH_SPACING * (int)scale;
}

static void draw_glyph(int x, int y, const uint8_t *glyph, uint8_t scale, uint32_t color) {
  for (int row = 0; row < TEXT_GLYPH_H; row++) {
    uint8_t bits = glyph[row];
    for (int col = 0; col < TEXT_GLYPH_W; col++) {
      if ((bits >> (TEXT_GLYPH_W - 1 - col)) & 0x1) {
        int px = x + col * (int)scale;
        int py = y + row * (int)scale;
        if (px < 0 || py < 0) continue;
        if (px + (int)scale > SCREEN_WIDTH || py + (int)scale > SCREEN_HEIGHT) continue;
        renderer_draw_rectangle((uint16_t)px, (uint16_t)py, scale, scale, color);
      }
    }
  }
}

void text_draw(int x, int y, const char *str, uint8_t scale, uint32_t color) {
  if (str == NULL) return;
  if (scale == 0) scale = 1;

  int advance = (TEXT_GLYPH_W + GLYPH_SPACING) * (int)scale;
  int cx = x;
  for (int i = 0; str[i] != '\0'; i++) {
    const uint8_t *glyph = glyph_for(str[i]);
    draw_glyph(cx, y, glyph, scale, color);
    cx += advance;
  }
}
